-- Faazio MVP — gateway-native superadmin email+password login (Partner Portal).
-- Authority: docs/architecture/web-portal.md ("Portal superadmin auth"), db-schema.md §12.18,
-- monolith-breakdown.md §1 (admins context), docs/RUNBOOKS/PORTAL_AUTH.md.
--
-- Why: the portal's superadmin sign-in was a mocked in-repo directory (demo1234). This migration is
-- the durable credential + refresh-session store the Go gateway mints sessions against. No GoTrue /
-- Firebase Web dependency is added; the gateway already owns RequireRole(SUPER_ADMIN) + audit logs.
--
-- Secrets never live here: no INSERT with emails/passwords/hashes ships in the repo. Seeding the two
-- superadmins is a manual, one-time SQL step using hashes generated by tools/hash-password (see the
-- PORTAL_AUTH runbook).
--
-- Lean dtype policy (§0.1): ids = TEXT slugs, time = TIMESTAMPTZ, JSONB guarded, writes service_role.

create schema if not exists admins;

create table if not exists admins.portal_users (
  user_id            text primary key,                 -- stable slug, e.g. 'pu-super-1'
  email              text not null,                    -- PII; unique case-insensitively below
  display_name       text not null default '',
  password_hash      text not null,                    -- Argon2id PHC string (pepper applied upstream)
  role               text not null default 'SUPER_ADMIN'
                     check (role in ('SUPER_ADMIN')),
  active             boolean not null default true,
  must_change        boolean not null default true,    -- forces rotation of the initial password
  failed_attempts    integer not null default 0 check (failed_attempts >= 0),
  locked_until       timestamptz,                      -- durable lockout (survives a Valkey outage)
  last_login_at      timestamptz,
  password_changed_at timestamptz not null default now(),
  created_at         timestamptz not null default now(),
  updated_at         timestamptz not null default now()
);
-- Case-insensitive email without a CITEXT extension dependency: the repo always lower()s on read.
create unique index if not exists portal_users_email_lower_uniq
  on admins.portal_users (lower(email));
create index if not exists portal_users_active_idx on admins.portal_users (active);

-- Rotating opaque refresh sessions. `token_hash` is SHA-256 of the raw token, so a DB leak does not
-- yield a usable session. One row per rotation; `session_id` is the family id used for reuse
-- detection (a replayed old token revokes the whole family).
create table if not exists admins.portal_sessions (
  token_hash  text primary key,                        -- sha256(raw refresh token), hex
  session_id  text not null,                           -- refresh family id (many rows per family)
  user_id     text not null references admins.portal_users (user_id) on delete cascade,
  expires_at  timestamptz not null,
  used_at     timestamptz,                             -- set once on rotation; a second use = theft
  revoked_at  timestamptz,
  ip_hash     text not null default '',                -- sha256(client ip) prefix; no raw IP
  created_at  timestamptz not null default now()
);
create index if not exists portal_sessions_family_idx on admins.portal_sessions (session_id);
create index if not exists portal_sessions_user_idx on admins.portal_sessions (user_id);
create index if not exists portal_sessions_expiry_idx on admins.portal_sessions (expires_at);

-- ---------------------------------------------------------------- RLS + grants (Supabase only)
-- The gateway connects as service_role (bypasses RLS) and is the only writer. Direct Supabase
-- clients never get SELECT: portal credential/session rows are never public API surface.
do $$
begin
  if not exists (select 1 from pg_namespace where nspname = 'auth')
     or not exists (select 1 from pg_roles where rolname = 'authenticated') then
    raise notice 'auth schema or Supabase roles absent — skipping 0032 RLS + grants (non-Supabase environment)';
    return;
  end if;

  grant usage on schema admins to anon, authenticated;
  execute 'alter table admins.portal_users enable row level security';
  execute 'alter table admins.portal_sessions enable row level security';
  execute 'revoke all on admins.portal_users from anon, authenticated';
  execute 'revoke all on admins.portal_sessions from anon, authenticated';
end;
$$;
